    function copyVoucherText(elementId, successMsg) {
        const textElement = document.getElementById(elementId);
        // Lấy text và bỏ đi dấu ngoặc kép ở hai đầu nếu có
        let text = textElement.innerText || textElement.textContent;
        if (text.startsWith('"') && text.endsWith('"')) {
            text = text.substring(1, text.length - 1);
        }
        
        // Use modern clipboard API if available and in secure context
        if (navigator.clipboard && window.isSecureContext) {
            navigator.clipboard.writeText(text).then(() => {
                showToast(successMsg);
            }).catch(err => {
                console.error('Error copying text: ', err);
                fallbackCopyTextToClipboard(text, successMsg);
            });
        } else {
            fallbackCopyTextToClipboard(text, successMsg);
        }
    }

    function fallbackCopyTextToClipboard(text, successMsg) {
        const textArea = document.createElement("textarea");
        textArea.value = text;
        
        // Avoid scrolling to bottom
        textArea.style.top = "0";
        textArea.style.left = "0";
        textArea.style.position = "fixed";

        document.body.appendChild(textArea);
        textArea.focus();
        textArea.select();

        try {
            const successful = document.execCommand('copy');
            if (successful) {
                showToast(successMsg);
            } else {
                console.error('Fallback: Copying text command was unsuccessful');
            }
        } catch (err) {
            console.error('Fallback: Oops, unable to copy', err);
        }

        document.body.removeChild(textArea);
    }

